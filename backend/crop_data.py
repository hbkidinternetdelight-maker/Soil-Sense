# List of supported crops
SUPPORTED_CROPS = list(CROP_DATA.keys())


def get_crop_data(crop):
    """
    Return complete data for a crop.
    """
    return CROP_DATA.get(crop)


def get_stage_data(crop, stage):
    """
    Return moisture settings for a particular crop and stage.
    """
    crop_data = CROP_DATA.get(crop)

    if not crop_data:
        return None

    return crop_data["stages"].get(stage)
